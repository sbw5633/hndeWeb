String? koreanHolidayName(DateTime d) {
  final int key = d.year * 10000 + d.month * 100 + d.day;
  return _holidaysByYear[d.year]?[key];
}

bool isKoreanHoliday(DateTime d) => koreanHolidayName(d) != null;

